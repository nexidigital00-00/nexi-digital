    strings["SOCCAP"] = " ".join(f"<span>{w}</span>" for w in soc.split())
    strings["WAVE"] = "".join(f'<i style="animation-delay:-{(i * 0.37) % 0.9:.2f}s"></i>' for i in range(18))
    html = tpl.replace("[[TICKER]]", "".join(f"<span>{t}</span>{SEP}" for t in ticker))
