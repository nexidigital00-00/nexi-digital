    for k, v in strings.items():
        html = html.replace(f"[[{k}]]", v)
    left = re.findall(r"\[\[[^\]]+\]\]", html)
    if left:
        sys.exit(f"{out}: unfilled {sorted(set(left))}")
    (SITE / out).write_text(html, encoding="utf-8")
